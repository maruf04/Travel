// Copies everything in public/data (categories, channels, videos) into a SQL file
// you can run in Supabase, so the data lives in the database instead of JSON files.
//
//   node scripts/make-seed.mjs                  reads public/data, writes supabase/seed.sql
//   node scripts/make-seed.mjs some/data supabase/seed.sql
//
// The file only INSERTS rows that are missing ("on conflict do nothing"), so running it
// again never overwrites edits you made on the edit page.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'

const dataDir = process.argv[2] || 'public/data'
const outFile = process.argv[3] || 'supabase/seed.sql'

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))

// ---- SQL value helpers ----
const str = (s) => (s == null || s === '' ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const num = (n) => (typeof n === 'number' && Number.isFinite(n) ? String(n) : 'null')
const arr = (a) => (a && a.length ? `array[${a.map((x) => str(x)).join(', ')}]::text[]` : `'{}'::text[]`)

function insertStatements(table, columns, rows, chunk = 40) {
  const out = []
  for (let i = 0; i < rows.length; i += chunk) {
    const part = rows.slice(i, i + chunk).map((r) => `  (${r.join(', ')})`).join(',\n')
    out.push(`insert into ${table} (${columns.join(', ')}) values\n${part}\non conflict (id) do nothing;\n`)
  }
  return out.join('\n')
}

// ---- read the JSON files ----
const categories = readJson(join(dataDir, 'categories.json'))
const channels = readJson(join(dataDir, 'channels.json'))

const byId = new Map()
for (const file of readdirSync(join(dataDir, 'videos')).filter((f) => f.endsWith('.json'))) {
  for (const v of readJson(join(dataDir, 'videos', file))) {
    const seen = byId.get(v.id)
    if (seen) seen.categories = [...new Set([...(seen.categories || []), ...(v.categories || [])])]
    else byId.set(v.id, { ...v })
  }
}
const videos = [...byId.values()]

// ---- build the SQL ----
const sql = []
sql.push(`-- Generated by scripts/make-seed.mjs on ${new Date().toISOString().slice(0, 10)}
-- ${categories.length} categories, ${channels.length} channels, ${videos.length} videos.
-- Run supabase/schema.sql first, then this file. Safe to run again: it only adds rows that are missing.
`)

sql.push('-- categories (the order here becomes the tab order)')
sql.push(insertStatements('categories', ['id', 'name', 'icon', 'color', 'sort'],
  categories.map((c, i) => [str(c.id), str(c.name), str(c.icon), str(c.color), String(i)])))

sql.push('-- channels')
sql.push(insertStatements('channels', ['id', 'name', 'country', 'url', 'youtube_id', 'logo', 'logo_credit'],
  channels.map((c) => [str(c.id), str(c.name), str(c.country), str(c.url), str(c.youtubeId), str(c.logo), str(c.logoCredit)])))

sql.push('-- videos')
sql.push(insertStatements('videos',
  ['id', 'channel', 'title', 'categories', 'countries', 'place_name', 'lat', 'lng', 'era_from', 'era_to'],
  videos.map((v) => [
    str(v.id), str(v.channel), str(v.title), arr(v.categories), arr(v.countries),
    str(v.place?.name), num(v.place?.lat), num(v.place?.lng), num(v.era?.from), num(v.era?.to),
  ])))

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, sql.join('\n'))
console.log(`Wrote ${outFile}: ${categories.length} categories, ${channels.length} channels, ${videos.length} videos`)
